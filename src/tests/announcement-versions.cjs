const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const esbuild = require('esbuild');
const code = esbuild.transformSync(fs.readFileSync(path.join(__dirname, '../features/home/announcementVersions.ts'), 'utf8'), { loader: 'ts', format: 'cjs' }).code;
const mod = { exports: {} };
new Function('exports', 'module', code)(mod.exports, mod);
const { announcementVersion: version, latestPopupAnnouncement: latest, announcementSeenKey: key } = mod.exports;
const first = { id: 1, version: 1, title: '公告', content: '原内容', is_popup: true, effective_date: '2026-11-19', created_at: '2026-11-19T00:00:00Z' };
assert.equal(version(first), version({ ...first }));
assert.notEqual(version(first), version({ ...first, version: 2 }));
assert.equal(version(first), version({ ...first, updated_at: '2026-11-20T00:00:00Z' }), 'only the server version controls acknowledgement');
assert.notEqual(key('guest'), key('123'));
assert.notEqual(key('123'), key('456'));
const second = { ...first, id: 2, effective_date: '2026-11-20' };
assert.equal(latest([first, second]).id, 1, 'keep authoritative response order');
assert.equal(latest([{ ...second, is_popup: false }, first]).id, 1);
assert.equal(latest([{ ...second, is_popup: false }]), null);
console.log('PASS: server version identity, account isolation, authoritative popup order');
